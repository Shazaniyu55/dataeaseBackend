/**
 * Check if an email is blocked.
 * Returns { blocked: true, reason } or { blocked: false }
 */
async function isEmailBlocked(email) {
  if (!email || typeof email !== "string") {
    return { blocked: true, reason: "Invalid email address" };
  }

  const normalized = email.trim().toLowerCase();
  const parts = normalized.split("@");

  if (parts.length !== 2) {
    return { blocked: true, reason: "Invalid email format" };
  }

  const domain = parts[1];

  // 1. Built-in disposable domain list (no DB hit needed)
  if (DISPOSABLE_DOMAINS.has(domain)) {
    return {
      blocked: true,
      reason: "Disposable email addresses are not allowed. Please use a real email.",
    };
  }

  // 2. Check DB blocklist — domain match OR exact email match
  const dbMatch = await BlockedEmail.findOne({
    isActive: true,
    $or: [
      { type: "domain", value: domain },
      { type: "email",  value: normalized },
    ],
  });

  if (dbMatch) {
    return {
      blocked: true,
      reason: dbMatch.reason || "This email is not allowed to register.",
    };
  }

  return { blocked: false };
}

